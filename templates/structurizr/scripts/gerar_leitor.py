def esc(texto: str) -> str:
    return html.escape(texto, quote=True)


def texto_de_html(h: str) -> str:
    h = re.sub(r"<(script|style)[^>]*>.*?</\1>", " ", h, flags=re.S)
    h = re.sub(r"</?(?:a|code|strong|em|del|span|mark)\b[^>]*>", "", h)  # marcação dentro da linha: sem espaço extra
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", " ", h))).strip()


# ------------------------------------------------------------ cabeçalho YAML simples dos ADRs

def _valor(v: str):
    v = v.strip()
    if v in ("", "~", "null", "[]"):
        return [] if v == "[]" else ""
    if v.startswith("[") and v.endswith("]"):
        return [_valor(x) for x in v[1:-1].split(",") if x.strip()]
    if len(v) >= 2 and v[0] == v[-1] and v[0] in "\"'":
        return v[1:-1]
    return v


def ler_frontmatter(texto: str) -> tuple[dict, str]:
    """Cabeçalho entre linhas "---": ``chave: valor``, ``chave: [a, b]`` ou ``chave:`` seguido de ``  - item``."""
    texto = texto.lstrip("\ufeff")
    if not texto.startswith("---"):
        return {}, texto
    linhas = texto.splitlines()
    fim = next((i for i in range(1, len(linhas)) if linhas[i].strip() == "---"), None)
    if fim is None:
        return {}, texto
    meta: dict = {}
    chave = None
    for linha in linhas[1:fim]:
        if not linha.strip() or linha.lstrip().startswith("#"):
            continue
        m = re.match(r"^\s+-\s*(.*)$", linha)
        if m and chave:
            if not isinstance(meta.get(chave), list):
                meta[chave] = []
            meta[chave].append(_valor(m.group(1)))
            continue
        m = re.match(r"^([A-Za-z_][\w-]*)\s*:\s*(.*)$", linha)
        if m:
            chave = m.group(1)
            meta[chave] = _valor(m.group(2))
    return meta, "\n".join(linhas[fim + 1:]).lstrip("\n")


def _lista(v) -> list[str]:
    if isinstance(v, list):
        return [str(x).strip() for x in v if str(x).strip()]
    return [s.strip() for s in str(v or "").split(",") if s.strip()]


def _status_canonico(valor: str) -> str:
    """Chave canônica do status do ADR: aceita a chave em português e o rótulo em inglês (accepted -> aceita)."""
    v = valor.strip().lower()
    return _STATUS_DE_ROTULO.get(v, v)


def ler_adr(arquivo: Path) -> dict:
    meta, corpo = ler_frontmatter(arquivo.read_text(encoding="utf-8"))
    num = re.match(r"(\d{4})-", arquivo.name)
    return {
        "arquivo": arquivo.name,
        "id": str(meta.get("id", "")).strip(),
        "id_arquivo": num.group(1) if num else "",
        "titulo": str(meta.get("titulo", "")).strip(),
        "status": _status_canonico(str(meta.get("status", ""))),
        "data": str(meta.get("data", "")).strip(),
        "date": str(meta.get("date", "")).strip(),
        "decisores": _lista(meta.get("decisores")),
        "elementos": _lista(meta.get("elementos")),
        "substitui": _lista(meta.get("substitui")),
        "substituida_por": _lista(meta.get("substituida_por")),
        "evidencia": _lista(meta.get("evidencia")),
        "aliases": _lista(meta.get("aliases")),
        "meta": meta,
        "corpo": corpo,
    }


def ler_adrs(pasta: Path) -> list[dict]:
    if not pasta.is_dir():
        return []
    return [ler_adr(f) for f in sorted(pasta.glob("*.md"))]


def validar_adrs(adrs: list[dict], identificadores: set[str] | None, idioma: str = "pt") -> list[str]:
    """Erros do formato único: campos, status, id, datas, seções, elementos e substituições recíprocas.

    As seções podem vir em português (Contexto, Decisão, Alternativas, Consequências) ou em inglês (Context, Decision,
    Alternatives, Consequences); o status, em português ou em inglês (accepted -> aceita). ``idioma`` só escolhe a
    língua das mensagens."""
    en = idioma == "en"
    erros: list[str] = []
    por_id = {}
    for a in adrs:
        nome = a["arquivo"]
        faltam = [c for c in CAMPOS_ADR if c not in a["meta"]]
        if faltam:
            erros.append(f"{nome}: missing header fields: {', '.join(faltam)}" if en
                         else f"{nome}: faltam campos no cabeçalho: {', '.join(faltam)}")
        if not re.fullmatch(r"\d{4}", a["id"]):
            erros.append(f"{nome}: id '{a['id']}' must have 4 digits" if en else f"{nome}: id '{a['id']}' precisa ter 4 dígitos")
        elif a["id"] != a["id_arquivo"]:
            erros.append(f"{nome}: id '{a['id']}' differs from the file number '{a['id_arquivo']}'" if en
                         else f"{nome}: id '{a['id']}' difere do número do arquivo '{a['id_arquivo']}'")
        if a["id"] in por_id:
            erros.append(f"{nome}: id '{a['id']}' repeated (also in {por_id[a['id']]['arquivo']})" if en
                         else f"{nome}: id '{a['id']}' repetido (também em {por_id[a['id']]['arquivo']})")
        por_id[a["id"]] = a
        if a["status"] not in STATUS_ADR:
            erros.append(f"{nome}: status '{a['status']}' invalid (use {', '.join(x.lower() for x in STATUS_ADR_EN.values())})"
                         if en else f"{nome}: status '{a['status']}' inválido (use {', '.join(STATUS_ADR)})")
        if not re.fullmatch(r"\d{4}-\d{2}-\d{2}", a["data"]):
            erros.append(f"{nome}: date '{a['data']}' not in YYYY-MM-DD format" if en
                         else f"{nome}: data '{a['data']}' fora do formato AAAA-MM-DD")
        if a["date"] and a["date"] != a["data"]:
            erros.append(f"{nome}: 'date' ({a['date']}) must repeat 'data' ({a['data']})" if en
                         else f"{nome}: 'date' ({a['date']}) precisa repetir 'data' ({a['data']})")
        if not a["titulo"]:
            erros.append(f"{nome}: empty title" if en else f"{nome}: título vazio")
        if not a["decisores"]:
            erros.append(f"{nome}: no decision makers" if en else f"{nome}: sem decisores")
        titulos = [m.group(1).strip() for m in re.finditer(r"(?m)^##\s+(.+)$", a["corpo"])]
        for s_pt, s_en in zip(SECOES_ADR, SECOES_ADR_EN):
            if s_pt not in titulos and s_en not in titulos:
                erros.append(f"{nome}: missing section '## {s_en}' (or '## {s_pt}')" if en else f"{nome}: falta a seção '## {s_pt}'")
        if identificadores is not None:
            for e in a["elementos"]:
                if e not in identificadores:
                    erros.append(f"{nome}: element '{e}' does not exist in the model" if en
                                 else f"{nome}: elemento '{e}' não existe no modelo")
        if a["status"] == "substituida" and not a["substituida_por"]:
            erros.append(f"{nome}: status 'substituida' without 'substituida_por'" if en
                         else f"{nome}: status 'substituida' sem 'substituida_por'")
        if a["substituida_por"] and a["status"] != "substituida":
            erros.append(f"{nome}: has 'substituida_por' but the status is '{a['status']}'" if en
                         else f"{nome}: tem 'substituida_por' mas o status é '{a['status']}'")
    for a in adrs:
        for alvo in a["substitui"]:
            b = por_id.get(alvo)
            if not b:
                erros.append(f"{a['arquivo']}: substitui '{alvo}', which does not exist" if en
                             else f"{a['arquivo']}: substitui '{alvo}', que não existe")
            elif a["id"] not in b["substituida_por"]:
                erros.append(f"{a['arquivo']}: substitui '{alvo}', but {b['arquivo']} does not say substituida_por: {a['id']}" if en
                             else f"{a['arquivo']}: substitui '{alvo}', mas {b['arquivo']} não diz substituida_por: {a['id']}")
        for alvo in a["substituida_por"]:
            b = por_id.get(alvo)
            if not b:
                erros.append(f"{a['arquivo']}: substituida_por '{alvo}', which does not exist" if en
                             else f"{a['arquivo']}: substituida_por '{alvo}', que não existe")
            elif a["id"] not in b["substitui"]:
                erros.append(f"{a['arquivo']}: substituida_por '{alvo}', but {b['arquivo']} does not say substitui: {a['id']}" if en
                             else f"{a['arquivo']}: substituida_por '{alvo}', mas {b['arquivo']} não diz substitui: {a['id']}")
    return erros


def identificadores_do_workspace(ws: dict) -> dict[str, dict]:
    """Identificador do DSL -> nome e tipo, para pessoas, sistemas, containers e componentes."""
    out: dict[str, dict] = {}

    def add(e, tipo):
        ident = e.get("properties", {}).get("structurizr.dsl.identifier", "")
        if ident:
            out[ident] = {"nome": e.get("name", ident), "tipo": tipo, "status": e.get("properties", {}).get("status", "")}

    m = ws.get("model", {})
    for p in m.get("people", []):
        add(p, "Pessoa")
    for s in m.get("softwareSystems", []):
        add(s, "Sistema")
        for c in s.get("containers", []):
            add(c, "Container")
            for k in c.get("components", []):
                add(k, "Componente")
    return out


