class Contexto:
    """Reescrita de links e referências ao mapa, comum a docs e ADRs."""

    def __init__(self, docs: set[str], adrs: dict[str, str], elementos: dict[str, dict], prefixo: str,
                 idioma: str = "pt"):
        self.docs = docs            # nomes de arquivo sem .md
        self.adrs = adrs            # nome de arquivo -> id
        self.elementos = elementos
        self.prefixo = prefixo      # âncora do documento atual (para os títulos)
        self.idioma = idioma        # "pt" ou "en": rótulos e dicas que o gerador escreve dentro do HTML
        self.toc: list[dict] = []
        self.usados: set[str] = set()

    def href(self, url: str, origem: str = "docs") -> tuple[str, bool]:
        """(href, externo). Links para .md viram âncoras do leitor; caminhos relativos apontam para a pasta de origem."""
        url = url.strip()
        if re.match(r"^[a-z][a-z0-9+.-]*:", url, re.I):
            return url, url.lower().startswith(("http:", "https:"))
        if url.startswith("#"):
            return f"#{self.prefixo}--{slug(url[1:])}", False
        caminho, _, frag = url.partition("#")
        nome = caminho.rsplit("/", 1)[-1]
        if nome.endswith(".md"):
            base = nome[:-3]
            if nome in self.adrs:
                return f"#adr-{self.adrs[nome]}", False
            if base in self.docs:
                return (f"#doc-{base}--{slug(frag)}" if frag else f"#doc-{base}"), False
        if caminho.startswith("../explorador/") or caminho.startswith("../leitor/"):
            return url, False
        return f"../{origem}/{url}" if caminho else url, False

    def titulo(self, nivel: int, texto_html: str) -> str:
        base = f"{self.prefixo}--{slug(texto_de_html(texto_html))}"
        ident, n = base, 2
        while ident in self.usados:
            ident, n = f"{base}-{n}", n + 1
        self.usados.add(ident)
        if nivel in (2, 3):
            self.toc.append({"id": ident, "titulo": texto_de_html(texto_html), "nivel": nivel})
        return f'<h{nivel} id="{ident}">{texto_html}</h{nivel}>'


_RE_TITULO = re.compile(r"^(#{1,6})\s+(.*?)\s*#*\s*$")
_RE_HR = re.compile(r"^\s{0,3}([-*_])(\s*\1){2,}\s*$")
_RE_CERCA = re.compile(r"^\s{0,3}(`{3,}|~{3,})\s*([\w+-]*)")
_RE_ITEM = re.compile(r"^(\s*)([-*+]|\d{1,9}[.)])\s+(.*)$")
_RE_SEP = re.compile(r"^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$")


def _t(ctx: Contexto, pt: str, en: str) -> str:
    return en if ctx.idioma == "en" else pt


def inline(texto: str, ctx: Contexto, origem: str = "docs") -> str:
    guardados: list[str] = []

    def guarda(h: str) -> str:
        guardados.append(h)
        return f"\x00{len(guardados) - 1}\x00"

    def codigo(m):
        conteudo = m.group(2).strip() if m.group(2).strip() else m.group(2)
        el = ctx.elementos.get(conteudo)
        if el:
            return guarda(f'<a class="ref-mapa" href="{MAPA}#{esc(conteudo)}" title="{esc(_t(ctx, "Ver", "View"))} {esc(el["nome"])} {esc(_t(ctx, "no mapa", "on the map"))}">'
                          f"<code>{esc(conteudo)}</code></a>")
        return guarda(f"<code>{esc(conteudo)}</code>")

    texto = re.sub(r"(`+)(.+?)\1", codigo, texto)
    texto = re.sub(r"\\([\\`*_{}\[\]()#+\-.!|~<>])", lambda m: guarda(esc(m.group(1))), texto)
    texto = re.sub(r"<(https?://[^>\s]+)>", lambda m: guarda(_link(m.group(1), esc(m.group(1)), ctx, origem)), texto)

    def link(m):
        rotulo = m.group(1)
        return guarda(_link(m.group(2), inline(rotulo, ctx, origem), ctx, origem))

    texto = re.sub(r"!\[([^\]]*)\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)", lambda m: guarda(esc(m.group(1) or m.group(2))), texto)
    texto = re.sub(r"\[([^\]]+)\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)", link, texto)
    texto = re.sub(r"(?<![\w\"'=/])(https?://[^\s<>()]+[^\s<>().,;:!?])",
                   lambda m: guarda(_link(m.group(1), esc(m.group(1)), ctx, origem)), texto)
    texto = esc(texto)
    texto = re.sub(r"\*\*(?=\S)(.+?)(?<=\S)\*\*", r"<strong>\1</strong>", texto)
    texto = re.sub(r"(?<!\w)__(?=\S)(.+?)(?<=\S)__(?!\w)", r"<strong>\1</strong>", texto)
    texto = re.sub(r"(?<![*\w])\*(?=[^\s*])(.+?)(?<=[^\s*])\*(?![*\w])", r"<em>\1</em>", texto)
    texto = re.sub(r"(?<![_\w])_(?=\S)(.+?)(?<=\S)_(?![_\w])", r"<em>\1</em>", texto)
    texto = re.sub(r"~~(?=\S)(.+?)(?<=\S)~~", r"<del>\1</del>", texto)
    for _ in range(3):  # links dentro de ênfase e vice-versa
        texto = re.sub(r"\x00(\d+)\x00", lambda m: guardados[int(m.group(1))], texto)
    return texto


def _link(url: str, rotulo_html: str, ctx: Contexto, origem: str) -> str:
    href, externo = ctx.href(url, origem)
    if externo:
        return f'<a href="{esc(href)}" rel="noopener noreferrer" target="_blank" class="externo">{rotulo_html}</a>'
    classe = ' class="ref-mapa"' if href.startswith(MAPA) else ""
    return f'<a href="{esc(href)}"{classe}>{rotulo_html}</a>'


def _celulas(linha: str) -> list[str]:
    s = linha.strip()
    if s.startswith("|"):
        s = s[1:]
    if s.endswith("|") and not s.endswith("\\|"):
        s = s[:-1]
    partes, atual, i = [], "", 0
    while i < len(s):
        if s[i] == "\\" and i + 1 < len(s) and s[i + 1] == "|":
            atual += "\\|"
            i += 2
            continue
        if s[i] == "|":
            partes.append(atual.strip())
            atual = ""
        else:
            atual += s[i]
        i += 1
    partes.append(atual.strip())
    return partes


def _tabela(linhas: list[str], ctx: Contexto, origem: str) -> str:
    cab = _celulas(linhas[0])
    alinh = []
    for c in _celulas(linhas[1]):
        c = c.strip()
        alinh.append("right" if c.endswith(":") and not c.startswith(":") else "center" if c.startswith(":") and c.endswith(":") else "")
    numerica = [a == "right" for a in alinh]

    def td(tag, i, c):
        cls = ' class="num"' if i < len(numerica) and numerica[i] else ""
        return f"<{tag}{cls}>{inline(c, ctx, origem)}</{tag}>"

    out = ['<div class="tabela"><table><thead><tr>']
    out += [td("th", i, c) for i, c in enumerate(cab)]
    out.append("</tr></thead><tbody>")
    for l in linhas[2:]:
        cels = _celulas(l)
        cels += [""] * (len(cab) - len(cels))
        out.append("<tr>" + "".join(td("td", i, c) for i, c in enumerate(cels[: len(cab)])) + "</tr>")
    out.append("</tbody></table></div>")
    return "".join(out)


def _inicio_de_bloco(linha: str, proxima: str | None) -> bool:
    return bool(_RE_TITULO.match(linha) or _RE_CERCA.match(linha) or _RE_HR.match(linha) or linha.lstrip().startswith(">")
                or _RE_ITEM.match(linha) or ("|" in linha and proxima is not None and _RE_SEP.match(proxima)))


def blocos(linhas: list[str], ctx: Contexto, origem: str = "docs") -> str:
    out: list[str] = []
    i, n = 0, len(linhas)
    while i < n:
        linha = linhas[i]
        if not linha.strip():
            i += 1
            continue
        m = _RE_CERCA.match(linha)
        if m:
            cerca, lang = m.group(1), m.group(2)
            corpo = []
            i += 1
            while i < n and not linhas[i].strip().startswith(cerca[0] * len(cerca)):
                corpo.append(linhas[i])
                i += 1
            i += 1
            rotulo = {"mermaid": _t(ctx, "Diagrama Mermaid", "Mermaid diagram"), "dsl": "Structurizr DSL"}.get(lang.lower(), lang)
            cab = f'<div class="codigo-rotulo">{esc(rotulo)}</div>' if rotulo else ""
            # Mermaid: o texto continua no HTML (busca, leitura sem script, falha ao desenhar); o leitor o desenha por cima.
            marca = ' class="codigo diagrama" data-diagrama="mermaid"' if lang.lower() == "mermaid" else ' class="codigo"'
            out.append(f'<figure{marca}>{cab}<pre tabindex="0"><code>{esc(chr(10).join(corpo))}</code></pre></figure>')
            continue
        m = _RE_TITULO.match(linha)
        if m:
            out.append(ctx.titulo(len(m.group(1)), inline(m.group(2), ctx, origem)))
            i += 1
            continue
        if _RE_HR.match(linha):
            out.append("<hr>")
            i += 1
            continue
        if "|" in linha and i + 1 < n and _RE_SEP.match(linhas[i + 1]):
            j = i + 2
            while j < n and linhas[j].strip() and "|" in linhas[j]:
                j += 1
            out.append(_tabela(linhas[i:j], ctx, origem))
            i = j
            continue
        if linha.lstrip().startswith(">"):
            corpo = []
            while i < n and linhas[i].lstrip().startswith(">"):
                corpo.append(re.sub(r"^\s*>\s?", "", linhas[i]))
                i += 1
            out.append(f"<blockquote>{blocos(corpo, ctx, origem)}</blockquote>")
            continue
        if _RE_ITEM.match(linha):
            m0 = _RE_ITEM.match(linha)
            base, ordenada = len(m0.group(1).expandtabs(4)), m0.group(2)[0].isdigit()

            def outro_tipo(l):  # item no mesmo nível com outro marcador (ul -> ol) começa outra lista
                m = _RE_ITEM.match(l)
                return bool(m) and len(m.group(1).expandtabs(4)) <= base + 1 and m.group(2)[0].isdigit() != ordenada

            j = i + 1
            while j < n:
                if outro_tipo(linhas[j]):
                    break
                if _RE_ITEM.match(linhas[j]) or (linhas[j].startswith((" ", "\t")) and linhas[j].strip()):
                    j += 1
                    continue
                if not linhas[j].strip() and j + 1 < n and not outro_tipo(linhas[j + 1]) \
                        and (_RE_ITEM.match(linhas[j + 1]) or linhas[j + 1].startswith(("  ", "\t"))):
                    j += 1
                    continue
                if linhas[j].strip() and not _inicio_de_bloco(linhas[j], linhas[j + 1] if j + 1 < n else None) \
                        and not _RE_ITEM.match(linhas[j]) and linhas[j - 1].strip():
                    j += 1  # continuação preguiçosa do item
                    continue
                break
            out.append(_lista_html(linhas[i:j], ctx, origem))
            i = j
            continue
        par = [linha.strip()]
        i += 1
        while i < n and linhas[i].strip() and not _inicio_de_bloco(linhas[i], linhas[i + 1] if i + 1 < n else None):
            par.append(linhas[i].strip())
            i += 1
        juntos = ""
        for k, p in enumerate(par):
            quebra = k < len(par) - 1 and p.endswith("\\")
            juntos += (p[:-1] if quebra else p) + ("\x01" if quebra else " ")
        h = inline(juntos.strip(), ctx, origem).replace("\x01", "<br>")
        out.append(f"<p>{h}</p>")
    return "\n".join(out)


def _lista_html(linhas: list[str], ctx: Contexto, origem: str) -> str:
    m0 = _RE_ITEM.match(linhas[0])
    base = len(m0.group(1).expandtabs(4))
    ordenada = m0.group(2)[0].isdigit()
    itens: list[dict] = []
    for l in linhas:
        m = _RE_ITEM.match(l)
        if m and len(m.group(1).expandtabs(4)) <= base + 1:
            itens.append({"recuo": len(m.group(1)) + len(m.group(2)) + 1, "linhas": [m.group(3)]})
        elif itens:
            itens[-1]["linhas"].append(l)
    # Lista frouxa: linha em branco entre itens (não conta a última de cada item).
    frouxa = any(not x.strip() for it in itens for x in it["linhas"][:-1])
    partes = []
    for it in itens:
        r = it["recuo"]
        corpo = [it["linhas"][0]] + [x[r:] if x[:r].strip() == "" else x.lstrip() for x in it["linhas"][1:]]
        h = blocos(corpo, ctx, origem)
        if not frouxa and h.startswith("<p>"):
            h = re.sub(r"^<p>(.*?)</p>", r"\1", h, count=1, flags=re.S)
        partes.append(f"<li>{h}</li>")
    inicio = ""
    if ordenada:
        num = int(re.match(r"\d+", m0.group(2)).group(0))
        inicio = f' start="{num}"' if num != 1 else ""
    tag = "ol" if ordenada else "ul"
    return f"<{tag}{inicio}>" + "".join(partes) + f"</{tag}>"


def markdown(texto: str, ctx: Contexto, origem: str = "docs") -> str:
    texto = re.sub(r"<!--.*?-->", "", texto, flags=re.S)
    return blocos(texto.replace("\r\n", "\n").split("\n"), ctx, origem)


# ------------------------------------------------------------ documentos e ADRs

def secao_do_doc(arquivo: str, texto: str) -> str:
    m = re.search(r"<!--\s*leitor:\s*(explicacao|guia|referencia)\s*-->", texto)
    if m:
        return m.group(1)
    if MARCA_GERADO in texto or MARCA_GERADO_EN in texto or arquivo.startswith("99-"):
        return "referencia"
    nome = arquivo.lower()
    if re.search(r"como-usar|como-|guia|passo-a-passo|tutorial|how-to|guide|step-by-step|getting-started", nome):
        return "guia"
    return "explicacao"


def _secoes_busca(ancora: str, titulo_doc: str, corpo_html: str, onde: str, chave: str = "") -> list[dict]:
    partes = re.split(r'(<h[1-4] id="[^"]+">.*?</h[1-4]>)', corpo_html, flags=re.S)
    out, atual_id, atual_tit = [], ancora, titulo_doc
    buf: list[str] = []

    def fecha():
        t = texto_de_html("".join(buf))
        if t or atual_id == ancora:
            out.append({"alvo": atual_id, "pagina": ancora, "titulo": atual_tit, "doc": titulo_doc, "onde": onde,
                        "ondeChave": chave, "texto": t[:4000]})

    for p in partes:
        m = re.match(r'<h[1-4] id="([^"]+)">(.*?)</h[1-4]>', p, flags=re.S)
        if m:
            fecha()
            buf = []
            atual_id, atual_tit = m.group(1), texto_de_html(m.group(2))
        else:
            buf.append(p)
    fecha()
    return out


def _resumo(corpo_html: str) -> str:
    m = re.search(r"<p>(.*?)</p>", corpo_html, flags=re.S)
    t = texto_de_html(m.group(1)) if m else ""
    return t if len(t) <= 220 else t[:217].rsplit(" ", 1)[0] + "…"


def _resumo_adr(corpo_html: str) -> str:
    """O que foi decidido: primeiro parágrafo da seção Decisão (sem ela, o primeiro parágrafo do ADR)."""
    m = re.search(r'<h2 id="[^"]*">(?:Decisão|Decision)</h2>\s*(<p>.*?</p>)', corpo_html, flags=re.S)
    return _resumo(m.group(1)) if m else _resumo(corpo_html)


def _git(base: Path, *args: str) -> str:
    try:
        r = subprocess.run(["git", "-C", str(base), *args], capture_output=True, text=True, encoding="utf-8", timeout=10)
    except (OSError, subprocess.SubprocessError):
        return ""
    return r.stdout.strip() if r.returncode == 0 else ""


def _norm_repo(url: str) -> str:
    """Forma comparável do remoto: `git@host:dono/repo`, `ssh://git@host[:porta]/dono/repo` (o que `url.insteadOf`
    produz, por exemplo no checkout do CircleCI) e `https://host/dono/repo` viram `host/dono/repo`."""
    u = url.strip().lower()
    u = re.sub(r"^git@([^:/]+):", r"\1/", u)
    u = re.sub(r"^[a-z+]+://", "", u)
    u = re.sub(r"^[^@/]+@", "", u)
    u = re.sub(r"^([^/:]+):\d+/", r"\1/", u)
    return re.sub(r"\.git$", "", u.rstrip("/"))


def _repo_mapeado(base: Path, cfg: dict) -> dict:
    """O que se sabe do repositório mapeado: caminhos do inventário e, se a pasta é um clone dele (origin igual a
    `repo_github`), a raiz do clone. Uma evidência só vira link se o caminho existe de fato no repositório mapeado."""
    caminhos: set[str] = set()
    inv = base / "inventario.json"
    if inv.is_file():
        try:
            caminhos = {m["caminho"] for m in json.loads(inv.read_text(encoding="utf-8-sig")).get("modulos", []) if m.get("caminho")}
        except (ValueError, AttributeError, TypeError):
            caminhos = set()
    raiz = None
    repo = cfg.get("repo_github") or ""
    topo = _git(base, "rev-parse", "--show-toplevel") if repo else ""
    if topo and _norm_repo(_git(base, "remote", "get-url", "origin")) == _norm_repo(repo):
        raiz = Path(topo)
    return {"caminhos": caminhos, "raiz": raiz, "base": base}


def _evidencia(item: str, cfg: dict, mapeado: dict | None = None) -> dict:
    if re.match(r"^https?://", item):
        return {"texto": item, "url": item}
    repo = (cfg.get("repo_github") or "").rstrip("/")
    ramo = cfg.get("ramo") or "main"
    caminho = re.sub(r"\s*\([^)]*\)\s*$", "", item.split("#", 1)[0]).strip()
    if not repo or not caminho or caminho.startswith(("/", "\\")) or ":" in caminho:
        return {"texto": item, "url": ""}
    m = mapeado or {"caminhos": set(), "raiz": None, "base": None}
    rel = None
    if caminho in m["caminhos"]:
        rel = caminho
    elif m["raiz"] is not None:
        for cand in (m["raiz"] / caminho, m["base"] / caminho):          # relativo à raiz do repositório ou à pasta do mapa
            if cand.is_file():
                rel = cand.resolve().relative_to(m["raiz"].resolve()).as_posix()
                break
    return {"texto": item, "url": f"{repo}/blob/{ramo}/{rel}" if rel else ""}


def montar(ws: dict, base: Path, cfg: dict) -> dict:
    idioma = idioma_de(cfg)
    en = idioma == "en"
    secoes_leitor = [(k, SECOES_LEITOR_EN[k][0], SECOES_LEITOR_EN[k][1]) if en else (k, t, d) for k, t, d in SECOES_LEITOR]
    rotulos_adr = STATUS_ADR_EN if en else STATUS_ADR
    elementos = identificadores_do_workspace(ws)
    pasta_docs, pasta_adrs = base / "docs", base / "adrs"
    arquivos_docs = sorted(pasta_docs.glob("*.md")) if pasta_docs.is_dir() else []
    adrs = ler_adrs(pasta_adrs)
    nomes_docs = {f.stem for f in arquivos_docs}
    mapa_adrs = {a["arquivo"]: (a["id"] or a["id_arquivo"]) for a in adrs}
    busca: list[dict] = []

    docs = []
    for f in arquivos_docs:
        if f.stem == INDICE_DECISOES:
            continue  # o índice gerado vira a seção Decisões do leitor
        texto = f.read_text(encoding="utf-8")
        ancora = f"doc-{f.stem}"
        ctx = Contexto(nomes_docs, mapa_adrs, elementos, ancora, idioma)
        corpo = markdown(texto, ctx, "docs")
        m = re.search(r"<h1[^>]*>(.*?)</h1>", corpo, flags=re.S)
        titulo = texto_de_html(m.group(1)) if m else f.stem
        corpo_sem_h1 = re.sub(r"<h1[^>]*>.*?</h1>\s*", "", corpo, count=1, flags=re.S)
        docs.append({
            "ancora": ancora, "arquivo": f"docs/{f.name}", "titulo": titulo, "secao": secao_do_doc(f.name, texto),
            "gerado": MARCA_GERADO in texto or MARCA_GERADO_EN in texto, "resumo": _resumo(corpo_sem_h1), "html": corpo_sem_h1, "toc": ctx.toc,
        })
        busca += _secoes_busca(ancora, titulo, corpo_sem_h1, dict((k, t) for k, t, _ in secoes_leitor)[docs[-1]["secao"]], docs[-1]["secao"])

    erros = validar_adrs(adrs, set(elementos) if elementos else None, idioma)
    mapeado = _repo_mapeado(base, cfg)
    lista_adrs = []
    for a in adrs:
        ident = a["id"] or a["id_arquivo"]
        ancora = f"adr-{ident}"
        ctx = Contexto(nomes_docs, mapa_adrs, elementos, ancora, idioma)
        corpo = markdown(a["corpo"], ctx, "adrs")
        corpo = re.sub(r"<h1[^>]*>.*?</h1>\s*", "", corpo, count=1, flags=re.S)
        titulo = a["titulo"] or a["arquivo"]
        lista_adrs.append({
            "ancora": ancora, "id": ident, "arquivo": f"adrs/{a['arquivo']}", "titulo": titulo,
            "status": a["status"], "statusRotulo": rotulos_adr.get(a["status"], a["status"] or ("no status" if en else "sem status")),
            "data": a["data"], "decisores": a["decisores"],
            "elementos": [{"ident": e, "nome": elementos.get(e, {}).get("nome", e), "tipo": elementos.get(e, {}).get("tipo", ""),
                           "existe": e in elementos} for e in a["elementos"]],
            "substitui": a["substitui"], "substituidaPor": a["substituida_por"], "aliases": a["aliases"],
            "evidencia": [_evidencia(x, cfg, mapeado) for x in a["evidencia"]],
            "resumo": _resumo_adr(corpo), "html": corpo, "toc": ctx.toc,
        })
        secoes = _secoes_busca(ancora, f"ADR {ident} · {titulo}", corpo, secoes_leitor[3][1], "decisoes")
        extra = [titulo, STATUS_ADR.get(a["status"], ""), STATUS_ADR_EN.get(a["status"], "")] + a["aliases"] + a["elementos"] + [elementos.get(e, {}).get("nome", "") for e in a["elementos"]]
        secoes[0]["texto"] = (" ".join(x for x in extra if x) + " " + secoes[0]["texto"]).strip()
        busca += secoes
    lista_adrs.sort(key=lambda x: (x["data"], x["id"]), reverse=True)

    return {
        "versao": 1,
        "idioma": idioma,
        "projeto": cfg.get("projeto") or ws.get("name", ""),
        "geradoEm": datetime.now().astimezone().isoformat(timespec="seconds"),
        "mapa": MAPA,
        "secoes": [{"chave": k, "titulo": t, "desc": d} for k, t, d in secoes_leitor],
        "docs": docs,
        "adrs": lista_adrs,
        "busca": busca,
        "avisos": erros,
    }


def main(argv: list[str]) -> int:
    if len(argv) < 3:
        print("Usage: python scripts/gerar_leitor.py <workspace.json> <output folder>"
              if os.environ.get("LODEMAP_IDIOMA", "").strip().lower() == "en" else __doc__)
        return 2
    ws = json.loads(Path(argv[1]).read_text(encoding="utf-8-sig"))
    destino = Path(argv[2])
    base = destino.resolve().parent
    cfg = ac.ler_config(base)  # lodemap.json + LODEMAP_IDIOMA; cfg["idioma"] sempre "pt" ou "en"
    dados = montar(ws, base, cfg)
    destino.mkdir(parents=True, exist_ok=True)
    js = ("// Gerado por scripts/gerar_leitor.py a partir de docs/ e adrs/. Não edite à mão.\n"
          "window.LEITOR_DADOS = " + json.dumps(dados, ensure_ascii=False, separators=(",", ":")) + ";\n")
    (destino / "dados.js").write_text(js, encoding="utf-8", newline="\n")
    for e in dados["avisos"]:
        print(("warning: " if idioma_de(cfg) == "en" else "aviso: ") + str(e), file=sys.stderr)
    if idioma_de(cfg) == "en":
        print(f"{len(dados['docs'])} documents and {len(dados['adrs'])} ADRs in {destino / 'dados.js'}"
              + (f"; {len(dados['avisos'])} ADR warnings" if dados["avisos"] else ""))
    else:
        print(f"{len(dados['docs'])} documentos e {len(dados['adrs'])} ADRs em {destino / 'dados.js'}"
              + (f"; {len(dados['avisos'])} avisos nos ADRs" if dados["avisos"] else ""))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
